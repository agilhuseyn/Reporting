const IDX = { az: 0, en: 1, ru: 2 };
export const LANGS = ['az', 'en', 'ru'];
const store = typeof localStorage !== 'undefined' ? localStorage : null;
let current = store?.getItem('hp_lang') || 'az';
if (!LANGS.includes(current)) current = 'az';

export const lang = () => current;
export function setLang(l) {
  current = l;
  store?.setItem('hp_lang', l);
  if (typeof window !== 'undefined') window.dispatchEvent(new Event('langchange'));
}

export function t(key) {
  const row = ROWS[key];
  if (!row) return key;
  return row[IDX[current]] || row[0];
}

export const hasKey = (k) => k in ROWS;

// o[`${prefix}_${lang}`] → yoxdursa az
export function label(o, prefix) {
  if (!o) return '';
  return o[`${prefix}_${current}`] || o[`${prefix}_az`] || '';
}

export function fmtNum(v, d = 2) {
  const n = Number(v);
  if (!Number.isFinite(n)) return String(v ?? '');
  return n.toLocaleString(current === 'en' ? 'en-US' : 'ru-RU', { minimumFractionDigits: d, maximumFractionDigits: d });
}
